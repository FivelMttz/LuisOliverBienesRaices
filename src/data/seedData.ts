/**
 * Simple deterministic hash for demo local account auth (not a server-side crypto secret).
 */
export function simpleLocalHash(raw: string): string {
  let h = 2166136261;
  for (let i = 0; i < raw.length; i++) {
    h ^= raw.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return `lh_${(h >>> 0).toString(16)}`;
}

